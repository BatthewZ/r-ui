import {
  Box,
  CalendarDays,
  ChartLine,
  ChevronsUpDown,
  Command,
  Compass,
  FileText,
  Filter,
  Folder,
  Image,
  Languages,
  Layers,
  ListOrdered,
  MessageSquareWarning,
  Palette,
  PanelsTopLeft,
  ShieldCheck,
  SlidersHorizontal,
  Sparkles,
  SquareKanban,
  Store,
  Table2,
  TextCursorInput,
  Wrench,
} from "lucide-react";
import type { ComponentType } from "react";

/** Each group's sidebar icon (the icon rail shows nothing else); a group not listed takes a folder. */
const ICONS: Record<string, ComponentType<{ className?: string }>> = {
  tokens: Palette,
  primitives: Box,
  feedback: MessageSquareWarning,
  form: TextCursorInput,
  dates: CalendarDays,
  disclosure: ChevronsUpDown,
  overlays: Layers,
  toolbar: Wrench,
  commands: Command,
  data: Table2,
  filters: Filter,
  boards: SquareKanban,
  charts: ChartLine,
  content: FileText,
  navigation: Compass,
  guards: ShieldCheck,
  steps: ListOrdered,
  layout: PanelsTopLeft,
  marketing: Store,
  media: Image,
  motion: Sparkles,
  preferences: SlidersHorizontal,
  locale: Languages,
};

export const groupIcon = (group: string) => ICONS[group] ?? Folder;
